/** Icono en su baldosa de color suave (tarjetas, objetos, deudas, imprevistos…) */
export function GlyphTile({ name, size = 44, color = 'var(--brand)', muted }: { name: string; size?: number; color?: string; muted?: boolean }) {
  const I = MAP[name as Glyph] ?? CircleHelp
  return (
    <span
      className="grid shrink-0 place-items-center rounded-[14px] transition-all"
      style={{ width: size, height: size, background: muted ? 'var(--fill)' : `color-mix(in srgb, ${color} 13%, var(--surface))`, color: muted ? 'var(--ink-3)' : color }}
      aria-hidden
    >
      <I size={Math.round(size * 0.5)} strokeWidth={1.8} />
    </span>
  )
}

/** Solo el icono, en línea con el texto */
export function Glyph({ name, size = 18, className }: { name: string; size?: number; className?: string }) {
  const I = MAP[name as Glyph] ?? CircleHelp
  return <I size={size} strokeWidth={1.8} className={className} aria-hidden />
}
